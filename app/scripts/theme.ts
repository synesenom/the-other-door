// docs/design/tokens.json -> CSS custom properties. The renderer reads colours,
// type, spacing and sizes from these variables only.

interface Tokens {
  color: { light: Record<string, { value: string }>; dark: Record<string, { value: string }> }
  font: Record<string, { family: string; fallback: string } | string>
  'type-scale': Record<string, { size: number; line: number; font: string; weight: number; tracking?: string }>
  space: number[]
  radius: Record<string, number>
  size: Record<string, number | Record<string, number>>
  phone: {
    'type-scale': Record<string, number>
    'tab-bar': Record<string, number | Record<string, number>>
    'action-bar': Record<string, number>
    'row-min-height': number
    gutter: number
  }
  shadow: { page: string }
}

const px = (n: number) => `${n}px`

function phone(t: Tokens): string[] {
  const out: string[] = []
  for (const [name, n] of Object.entries(t.phone['type-scale'])) out.push(`--phone-text-${name}-size: ${px(n)}`)
  for (const group of ['tab-bar', 'action-bar'] as const) {
    for (const [k, v] of Object.entries(t.phone[group])) {
      if (typeof v === 'number') out.push(`--phone-${group}-${k}: ${px(v)}`)
      else for (const [k2, n] of Object.entries(v)) out.push(`--phone-${group}-${k}-${k2}: ${px(n)}`)
    }
  }
  out.push(`--phone-row-min-height: ${px(t.phone['row-min-height'])}`)
  out.push(`--phone-gutter: ${px(t.phone.gutter)}`)
  return out
}

function light(t: Tokens): string[] {
  const out: string[] = []
  for (const [name, { value }] of Object.entries(t.color.light)) out.push(`--color-${name}: ${value}`)
  for (const [role, f] of Object.entries(t.font)) {
    if (typeof f === 'string') continue
    out.push(`--font-${role}: "${f.family}", ${f.fallback}`)
  }
  for (const [name, s] of Object.entries(t['type-scale'])) {
    out.push(`--text-${name}-size: ${px(s.size)}`)
    out.push(`--text-${name}-line: ${s.line}`)
    out.push(`--text-${name}-font: var(--font-${s.font})`)
    out.push(`--text-${name}-weight: ${s.weight}`)
    if (s.tracking) out.push(`--text-${name}-tracking: ${s.tracking}`)
  }
  t.space.forEach((n, i) => out.push(`--space-${i + 1}: ${px(n)}`))
  for (const [name, n] of Object.entries(t.radius)) out.push(`--radius-${name}: ${px(n)}`)
  for (const [name, v] of Object.entries(t.size)) {
    if (typeof v === 'number') out.push(`--size-${name}: ${px(v)}`)
    else for (const [k, n] of Object.entries(v)) out.push(`--size-${name}-${k}: ${px(n)}`)
  }
  out.push(`--shadow-page: ${t.shadow.page}`)
  out.push(...phone(t))
  return out
}

function dark(t: Tokens): string[] {
  return Object.entries(t.color.dark).map(([name, { value }]) => `--color-${name}: ${value}`)
}

const lines = (decls: string[], indent: string) => decls.map((d) => `${indent}${d};`).join('\n')

export function generateTheme(tokens: Tokens): string {
  const d = dark(tokens)
  return [
    '/* Generated by `npm run gen-theme` from docs/design/tokens.json. Do not edit. */',
    ':root {',
    lines(light(tokens), '  '),
    '}',
    '',
    '@media (prefers-color-scheme: dark) {',
    '  :root:not([data-theme="light"]) {',
    lines(d, '    '),
    '  }',
    '}',
    '',
    '[data-theme="dark"] {',
    lines(d, '  '),
    '}',
    '',
  ].join('\n')
}
